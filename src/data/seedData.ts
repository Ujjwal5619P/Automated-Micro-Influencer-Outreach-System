// Helper to evaluate qualification against standard criteria
export function evaluateCreatorQualification(
  creator: {
    subscribers: number;
    engagementRate: number;
    uploadsLast90Days: number;
    topics: string[];
    niche: string;
  },
  criteria: FilterCriteria = DEFAULT_FILTER_CRITERIA
) {
  const reasons: string[] = [];
  
  // Follower range check
  if (creator.subscribers < criteria.minFollowers) {
    reasons.push(`Subscriber count (${creator.subscribers.toLocaleString()}) is below minimum ${criteria.minFollowers.toLocaleString()}`);
  } else if (creator.subscribers > criteria.maxFollowers) {
    reasons.push(`Subscriber count (${creator.subscribers.toLocaleString()}) exceeds micro-influencer cap of ${criteria.maxFollowers.toLocaleString()}`);
  }

  // Engagement check
  if (creator.engagementRate < criteria.minEngagementRate) {
    reasons.push(`Engagement rate (${creator.engagementRate.toFixed(1)}%) is below ${criteria.minEngagementRate}% threshold`);
  }

  // Activity check
  if (creator.uploadsLast90Days < criteria.minUploads90Days) {
    reasons.push(`Upload activity (${creator.uploadsLast90Days} uploads in 90 days) is below required ${criteria.minUploads90Days} uploads`);
  }

  // Topic match
  const hasKeyword = criteria.requiredKeywords.some(kw => 
    creator.topics.some(t => t.toLowerCase().includes(kw.toLowerCase())) ||
    creator.niche.toLowerCase().includes(kw.toLowerCase())
  );
  if (!hasKeyword) {
    reasons.push(`Content topics do not sufficiently match target keywords (${criteria.requiredKeywords.slice(0, 3).join(', ')})`);
  }

  const passed = reasons.length === 0;

  // Compute sub-scores (0-100)
  const relScore = hasKeyword ? Math.min(100, 75 + creator.topics.length * 5) : 35;
  const engRatio = creator.engagementRate / criteria.minEngagementRate;
  const engScore = Math.min(100, Math.round(Math.min(engRatio, 2.5) * 40));
  const actScore = Math.min(100, Math.round((creator.uploadsLast90Days / Math.max(criteria.minUploads90Days, 1)) * 30 + 30));
  const overall = passed 
    ? Math.round(relScore * 0.4 + engScore * 0.35 + actScore * 0.25)
    : Math.max(25, Math.round((relScore * 0.4 + engScore * 0.35 + actScore * 0.25) * 0.6));

  return {
    passed,
    relevanceScore: relScore,
    engagementScore: engScore,
    activityScore: actScore,
    overallScore: overall,
    rejectionReasons: reasons,
  };
}

